interface LanguageContextValue {
  language: Language;
  locale: string;
  languageShortcut: string;
  setLanguage: (language: Language) => void;
  cycleLanguage: () => void;
  t: (text: string) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

function isLanguage(value: string | null): value is Language {
  return value === "en" || value === "ar" || value === "fr" || value === "de";
}

function detectSystemLanguage(): Language {
  if (typeof navigator === "undefined") return "en";
  for (const locale of navigator.languages?.length ? navigator.languages : [navigator.language]) {
    const language = locale.split("-")[0]?.toLowerCase() ?? null;
    if (isLanguage(language)) return language;
  }
  return "en";
}

function getInitialLanguage(): Language {
  try {
    const stored = localStorage.getItem(LANGUAGE_KEY);
    if (isLanguage(stored)) return stored;
  } catch (error) {
    console.error("Could not read the saved app language:", error);
  }
  return detectSystemLanguage();
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(getInitialLanguage);
  const cycleLanguage = useCallback(() => {
    setLanguage((current) => {
      const currentIndex = languageOrder.indexOf(current);
      return languageOrder[(currentIndex + 1) % languageOrder.length] ?? "en";
    });
  }, []);
  const value = useMemo<LanguageContextValue>(() => ({
    language,
    locale: localeCodes[language],
    languageShortcut,
    setLanguage,
    cycleLanguage,
    t: (text) => language === "en" ? studioEnglishLabels[text] ?? text : studioTranslations[language]?.[text] ?? translations[language][text] ?? text,
  }), [language, cycleLanguage]);

  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
    try {
      if (localStorage.getItem(LANGUAGE_KEY) !== language) {
        localStorage.setItem(LANGUAGE_KEY, language);
      }
    } catch (error) {
      console.error("Could not save the app language:", error);
    }
  }, [language]);

  useEffect(() => {
    const syncLanguage = (event: StorageEvent) => {
      if (event.key && event.key !== LANGUAGE_KEY) return;
      if (isLanguage(event.newValue)) setLanguage(event.newValue);
    };
    window.addEventListener("storage", syncLanguage);
    return () => window.removeEventListener("storage", syncLanguage);
  }, []);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage(): LanguageContextValue {
  const value = useContext(LanguageContext);
  if (!value) throw new Error("useLanguage must be used within a LanguageProvider.");
  return value;
}

export function LanguagePicker() {
  const { language, setLanguage, languageShortcut, t } = useLanguage();
  return (
    <fieldset className="language-picker p-4">
    
      <div className="language-options" role="group" aria-label={t("Language")}>
        {languageOrder.map((choice) => (
          <button
            type="button"
            className={`language-option ${language === choice ? "selected" : ""}`}
            key={choice}
            aria-pressed={language === choice}
            onClick={() => setLanguage(choice)}
          >
            <span className="language-option-code" aria-hidden="true">{choice.toUpperCase()}</span>
            <span className="language-option-details"><strong>{languageNames[choice]}</strong></span>
            {language === choice && <Check size={15} aria-hidden="true" />}
          </button>
        ))}
      </div>
      <p className="language-shortcut"><Keyboard size={13} />{t("Cycle through languages")} <kbd>{languageShortcut}</kbd></p>
    </fieldset>
  );
}
